    want(three.count() == 3,
         f"«Yasaka Shrine, Maruyama Park, Chion-in» — три ссылки ({three.count()})")
    first.locator("summary").click()
    phone.wait_for_timeout(120)
    contrast(phone, "390")
    phone.screenshot(path=str(SHOTS / "japan-phone-new.png"), full_page=True)

    # ── страница светлая при любой настройке телефона.
    #
    # Это не перестраховка: тёмная тема тут была, включалась сама по настройке
    # устройства, и ровно её Ни и увидела словами «сложно читать». Проверять
    # это глазами бесполезно — на нашей машине светло всегда. Поэтому браузер
    # открывается с включённым тёмным режимом и меряется настоящий цвет фона.
    night = browser.new_page(viewport=DESK, color_scheme="dark")
    night.goto(PAGE.as_uri(), wait_until="load")
    night.wait_for_timeout(150)
    paint = night.evaluate("""() => {
      const root = getComputedStyle(document.documentElement);
      return { bg: root.backgroundColor, spots: root.backgroundImage,
               body: getComputedStyle(document.body).backgroundColor,
               ink: getComputedStyle(document.body).color, scheme: root.colorScheme };
    }""")
    # Цвет прибит, а не проверен на «достаточно светлый»: правило здесь не
    # про яркость, а про то, что тёмная тема не включилась сама.
    #
    # Спрашивается он у `html`, а не у `body`: с 24 августа бумага лежит на
    # корне (там же, откуда берётся область для процентов перелива), а `body`
    # обязан быть прозрачным — иначе его заливка во всю страницу закрыла бы
    # перелив целиком. #faf5f9 — её «менее синим, более белым» вместо
    # холодного #e8eef7.
    want(paint["bg"] == "rgb(250, 245, 249)",
         f'фон остаётся светлым при тёмной настройке устройства ({paint["bg"]})')
    want(paint["body"] == "rgba(0, 0, 0, 0)",
         f'бумага не закрыта сплошной заливкой поверх перелива ({paint["body"]})')
    # И сам перелив на месте: четыре пятна, а не одно «none». Проверяется
    # здесь, потому что тёмная настройка — это ещё и другой набор правил.
    want(paint["spots"].count("radial-gradient") == 4,
         f'перелив на месте, пятен четыре ({paint["spots"][:60]}…)')
    contrast(night, "тёмная настройка устройства")

    # ── забытая запись-место: считается в деньгах и обязана быть видна
    #
    # Ради чего эта проверка написана. 24 августа блок «хочу сходить» ушёл из
    # карточек городов — а вместе с ним и единственное место, где показывалась
    # её собственная запись вида `place`. Цена такой записи при этом
    # по-прежнему идёт в общий чек. Запись, которая берёт деньги и не видна
    # нигде, хуже лишнего блока: сумма растёт, а спросить с неё нечего, и
    # заметить это можно только сложив чек руками.
    #
    # Своих записей у Ни сейчас нет ни одной, поэтому проверять их на
    # собранной странице нечем: они приезжают из хранилища уже в браузере.
    # Хранилище тут поддельное — страница отдаётся своим http-сервером (с
    # `file://` браузер до перехвата не доходит: он обрывает запрос раньше),
    # а `/api/entries` отвечает одним местом с ценой. Так проверяется ровно
    # показ, без `wrangler` и без права стереть её настоящие записи.
    fake = {
        "ok": True,
        "ticks": {},
        "entries": [{
            "id": "probe-place", "kind": "place", "title": "Кофейня у Асакусы",
            "stay": "omo3", "amount": 1800, "currency": "jpy",
            "state": "onsite", "note": "проба показа",
        }],
    }
    served = ThreadingHTTPServer(("127.0.0.1", 0), _quiet_files(PAGE.parent))
    Thread(target=served.serve_forever, daemon=True).start()
    try:
        store = browser.new_page(viewport=DESK)
        store.route("**/api/entries", lambda route: route.fulfill(
            status=200, content_type="application/json", body=json.dumps(fake)))
        store.goto(f"http://127.0.0.1:{served.server_address[1]}/index.html",
                   wait_until="load")
        # `state="attached"`, а не «видима»: сначала строка ждётся в разметке —
        # видимой она станет, когда откроется свёртка, и это следующий вопрос.
        #
        # Пропажа ловится через `try`, а не падением: именно она — та беда, ради
        # которой всё это написано, и рассказать про неё тест обязан красной
        # строкой вместе с остальными, а не обвалом в середине прогона.
        try:
            store.wait_for_selector("[data-mine-place] .own", state="attached",
                                    timeout=5000)
            found = store.locator("[data-mine-place] .own").count()
        except PWTimeout:
            found = 0
        want(found == 1, f"записанное ею место нашлось на странице ({found})")

        if found == 1:
            line = store.locator("[data-mine-place] .own").first
            # Лежит она там же, где брони, — в «куплено отдельно». Это условие,
            # а не наблюдение: место, оставшееся вне её списка записей, читается
            # как пропавшее, сколько бы разметки под ним ни было.
            want(store.locator('[data-fold="bought"] [data-mine-place] .own').count() == 1,
                 "место лежит рядом с бронями, в «куплено отдельно»")
            # Видна — значит видна глазами, а не «есть в разметке»: свёртка
            # закрыта по умолчанию, и внутри неё `is_visible()` честно скажет
            # «нет». Поэтому она сначала открывается — ровно тем же одним
            # нажатием, каким Ни добирается до собственных броней.
            want(not line.is_visible(), "пока раздел свёрнут — не видна, как и брони")
            store.locator('[data-fold="bought"] > summary').click()
            store.wait_for_timeout(150)
            want(line.is_visible(), "и она видна, когда раздел открыт")
            said = " ".join(line.inner_text().split())
            for word in ("Кофейня у Асакусы", "Токио", "1 800", "правка", "убрать"):
                want(word.replace(" ", " ") in said.replace(" ", " "),
                     f'в строке есть «{word}» ({said})')
        # И то же число доехало до чека — иначе «видна» означало бы только
        # «нарисована», а деньги остались бы сами по себе. Спрашивается это
        # даже когда строка не нашлась: тогда и видно, что деньги посчитаны
        # без неё — то самое «считается и не показывается».
        parts = " ".join(store.locator("#check [data-parts]").inner_text().split())
        want("места" in parts and "1 800" in parts.replace(" ", " "),
             f"чек называет её место отдельной строкой ({parts})")
        store.close()
    finally:
        served.shutdown()

    browser.close()

